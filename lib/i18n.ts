export const messages = { uz, ru, en } as const;

function resolve(path: string, tree: Record<string, unknown>): string {
  const parts = path.split('.');
  let cur: unknown = tree;
  for (const p of parts) {
    if (cur === undefined || cur === null || typeof cur !== 'object') break;
    cur = (cur as Record<string, unknown>)[p];
  }
  return typeof cur === 'string' ? cur : path;
}

export function translate(
  locale: Locale,
  path: string,
  vars?: Record<string, string | number>
): string {
  let s = resolve(path, messages[locale] as unknown as Record<string, unknown>);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      const needle = `{${k}}`;
      s = s.split(needle).join(String(v));
    }
  }
  return s;
}
